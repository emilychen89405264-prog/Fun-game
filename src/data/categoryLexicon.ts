// In-memory cache for online verification results
const onlineVerificationCache = new Map<
  string,
  { isValid: boolean; accuracyScore: number; reason: string }
>();

/**
 * Hybrid Local + Free Online Knowledge Graph Verification (Wikipedia / Wiktionary API, No API Key Required):
 * 1. First checks the fast local dictionary & semantic roots (< 1ms).
 * 2. If not in the local answer bank, queries Chinese Wikipedia & Wiktionary public open endpoints
 *    to verify whether the employee's word genuinely belongs to the category!
 */
export async function evaluateWordWithOnlineVerification(
  word: string,
  category: RoundCategory
): Promise<{ isValid: boolean; accuracyScore: number; reason: string }> {
  const cleanWord = word.trim();
  const cacheKey = `${category.title}::${cleanWord.toLowerCase()}`;

  if (onlineVerificationCache.has(cacheKey)) {
    return onlineVerificationCache.get(cacheKey)!;
  }

  // Step 1: Fast Local Check
  const localResult = evaluateWordLocally(cleanWord, category);
  if (localResult.isValid) {
    onlineVerificationCache.set(cacheKey, localResult);
    return localResult;
  }

  // If basic format is invalid (empty, pure numbers/symbols, or identical to category title), return immediately
  if (
    !cleanWord ||
    cleanWord.length > 20 ||
    /^[0-9\s\p{P}+=~<>|]+$/u.test(cleanWord) ||
    cleanWord === category.title
  ) {
    return localResult;
  }

  // Step 2: Query Free Public Wikipedia & Wiktionary Open APIs (Zero API Key Needed)
  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 3200);

    // Search Chinese Wikipedia with snippet & categories
    const wikiUrl = `https://zh.wikipedia.org/w/api.php?action=query&list=search&srsearch=${encodeURIComponent(
      cleanWord
    )}&utf8=1&format=json&srlimit=3`;

    const wikiRes = await fetch(wikiUrl, {
      signal: controller.signal,
      headers: {
        'User-Agent': 'LexiRush-TeamGame/1.0 (Enterprise Brainstorming Educational Game)',
      },
    });
    clearTimeout(timeoutId);

    if (wikiRes.ok) {
      const data = (await wikiRes.json()) as {
        query?: {
          search?: Array<{ title: string; snippet: string }>;
        };
      };

      const searchResults = data?.query?.search || [];
      if (searchResults.length > 0) {
        // Combine top 3 titles and snippets (strip HTML tags)
        const combinedText = searchResults
          .map((item) => `${item.title} ${item.snippet.replace(/<[^>]+>/g, '')}`)
          .join(' ');

        const indicators = WIKI_CATEGORY_INDICATORS[category.title] || [category.title];
        const matchedIndicator = indicators.find((ind) => combinedText.includes(ind));

        // Check if the search result actually relates to the submitted word
        const topTitle = searchResults[0].title.toLowerCase();
        const wordLower = cleanWord.toLowerCase();
        const isTitleRelevant =
          topTitle.includes(wordLower) ||
          wordLower.includes(topTitle) ||
          combinedText.toLowerCase().includes(wordLower);

        if (isTitleRelevant && matchedIndicator) {
          const verifiedResult = {
            isValid: true,
            accuracyScore: 88,
            reason: `網路百科驗證通過（符合「${matchedIndicator}」特徵）`,
          };
          onlineVerificationCache.set(cacheKey, verifiedResult);

          // Dynamically learn this word into the local knowledge base for future instant lookup!
          const kbEntry = CATEGORY_KNOWLEDGE_BASE.find((e) => e.title === category.title);
          if (kbEntry && !kbEntry.keywords.includes(cleanWord)) {
            kbEntry.keywords.push(cleanWord);
          }

          return verifiedResult;
        }
      }
    }

    // Special fallback for 4-character idioms via Wiktionary if not in local bank
    if (category.title === '四字成語' && cleanWord.length === 4) {
      const wiktUrl = `https://zh.wiktionary.org/w/api.php?action=query&titles=${encodeURIComponent(
        cleanWord
      )}&format=json`;
      const wiktRes = await fetch(wiktUrl, {
        headers: {
          'User-Agent': 'LexiRush-TeamGame/1.0',
        },
      });
      if (wiktRes.ok) {
        const wiktData = (await wiktRes.json()) as {
          query?: { pages?: Record<string, { missing?: string }> };
        };
        const pages = wiktData?.query?.pages || {};
        const pageExists = Object.keys(pages).some((k) => k !== '-1' && !pages[k].missing);
        if (pageExists) {
          const wiktVerified = {
            isValid: true,
            accuracyScore: 92,
            reason: '網路辭典驗證為正式四字成語',
          };
          onlineVerificationCache.set(cacheKey, wiktVerified);
          return wiktVerified;
        }
      }
    }
  } catch (err) {
    console.error('Online Wikipedia verification fallback error:', err);
  }

  const rejectedResult = {
    isValid: false,
    accuracyScore: 0,
    reason: `經題庫與網路檢索未符合「${category.title}」`,
  };
  onlineVerificationCache.set(cacheKey, rejectedResult);
  return rejectedResult;
}

