export function getCategoriesByIds(ids: string[]): RoundCategory[] {
  const validEntries = ids
    .map((id) => CATEGORY_KNOWLEDGE_BASE.find((item) => item.id === id))
    .filter((item): item is CategoryBankEntry => Boolean(item));

  const finalEntries =
    validEntries.length > 0
      ? validEntries
      : CATEGORY_KNOWLEDGE_BASE.slice(0, 5);

  return finalEntries.map((entry, idx) => ({
    roundNumber: idx + 1,
    title: entry.title,
    description: entry.description,
    examples: entry.examples,
    difficulty: entry.difficulty,
  }));
}

/**
 * Pure Local Zero-API Word Scoring Engine:
 * Evaluates a word against the current RoundCategory in < 1ms without any external API call.
 */
export function evaluateWordLocally(
  word: string,
  category: RoundCategory
): { isValid: boolean; accuracyScore: number; reason: string } {
  const cleanWord = word.trim();

  if (!cleanWord || cleanWord.length > 20) {
    return { isValid: false, accuracyScore: 0, reason: '詞彙長度不符規範' };
  }
  if (/^[0-9\s\p{P}+=~<>|]+$/u.test(cleanWord)) {
    return { isValid: false, accuracyScore: 0, reason: '請輸入有效文字詞彙' };
  }
  if (cleanWord === category.title) {
    return { isValid: false, accuracyScore: 0, reason: '不可直接輸入題目名稱本身' };
  }

  const kbEntry = CATEGORY_KNOWLEDGE_BASE.find(
    (entry) => entry.title === category.title || category.title.includes(entry.title)
  );

  // Special check for 4-character idioms
  if (category.title === '四字成語' || category.title.includes('成語')) {
    if (kbEntry && kbEntry.keywords.includes(cleanWord)) {
      return {
        isValid: true,
        accuracyScore: 98,
        reason: '精準命中四字成語詞庫',
      };
    }
    if (!/^[\u4e00-\u9fa5]{4}$/.test(cleanWord)) {
      return {
        isValid: false,
        accuracyScore: 0,
        reason: '需為四個中文字之成語',
      };
    }
    // If it is 4 Chinese characters but not in local keywords, return false here
    // so evaluateWordWithOnlineVerification will query online Wiktionary / Wikipedia!
    return {
      isValid: false,
      accuracyScore: 0,
      reason: '待網路辭典驗證',
    };
  }

  if (kbEntry) {
    // 1. Exact match in curated dictionary -> Highest accuracy (90 - 100)
    const exactMatch = kbEntry.keywords.some(
      (k) => k.toLowerCase() === cleanWord.toLowerCase()
    );
    if (exactMatch) {
      const specificityBonus = Math.min(10, Math.max(2, cleanWord.length * 2));
      return {
        isValid: true,
        accuracyScore: 90 + specificityBonus,
        reason: `精準命中「${category.title}」核心詞庫`,
      };
    }

    // 2. Partial match with dictionary keyword (e.g., "非洲大象" contains "大象")
    const partialKeywordMatch = kbEntry.keywords.find(
      (k) =>
        k.length >= 2 &&
        (cleanWord.toLowerCase().includes(k.toLowerCase()) ||
          k.toLowerCase().includes(cleanWord.toLowerCase()))
    );
    if (partialKeywordMatch && cleanWord.length >= 2) {
      const specificityBonus = Math.min(12, cleanWord.length * 2);
      return {
        isValid: true,
        accuracyScore: 82 + specificityBonus,
        reason: `符合「${partialKeywordMatch}」衍生關聯詞彙`,
      };
    }

    // 3. Semantic root / suffix match
    const rootMatch = kbEntry.substrings.find((sub) => cleanWord.includes(sub));
    if (rootMatch && cleanWord.length >= 2) {
      return {
        isValid: true,
        accuracyScore: 80 + Math.min(10, cleanWord.length * 2),
        reason: `具備「${rootMatch}」語意特徵認證通過`,
      };
    }
  }

  // 4. Check examples provided in category
  if (
    category.examples &&
    category.examples.some((ex) => ex.toLowerCase() === cleanWord.toLowerCase())
  ) {
    return {
      isValid: true,
      accuracyScore: 95,
      reason: '命中題目精選範例詞彙',
    };
  }

  return {
    isValid: false,
    accuracyScore: 0,
    reason: `未匹配「${category.title}」詞庫特徵`,
  };
}

